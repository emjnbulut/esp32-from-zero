// Bundle a lesson's sketches for the full-code cards: node tools/sketches.mjs ep04 04-buttons-and-millis
// -> <ep>/sketches.js with const SKETCHES = { name: "source", ... } (read by fullCode() in the episode script)
import fs from "fs";
import path from "path";
const [ep, lesson] = process.argv.slice(2);
const dir = path.join("..", "lessons", lesson, "code");
const out = {};
for (const name of fs.readdirSync(dir)) {
  const f = path.join(dir, name, name + ".ino");
  if (fs.existsSync(f)) out[name] = fs.readFileSync(f, "utf8").replace(/\r\n/g, "\n");
}
fs.writeFileSync(path.join(ep, "sketches.js"), `// generated by tools/sketches.mjs from lessons/${lesson}/code - do not edit\nconst SKETCHES = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.keys(out).join(", "));
