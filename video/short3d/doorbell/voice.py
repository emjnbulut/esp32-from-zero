"""Narration for the phone-doorbell Short (Episode 12 phone control), EN or TR (creator's cloned voice, cbx.settings({}, lang)).

    .venv/Scripts/python video/short3d/doorbell/voice.py --lang en            # narrate, Whisper retakes, schedule
    .venv/Scripts/python video/short3d/doorbell/voice.py --lang tr --schedule # only rebuild voice.wav + schedule.json

0. short.json (both languages, the format tools/cbx_retake.py --short reads) is generated from script_en.json +
   script_tr.json (the texts live there) and VIS below (which shot each line belongs to)
1. every line is narrated into build/<lang>/<id>.mp3 (cached by text + voice settings in build/<lang>/cbx_cache.json)
2. tools/cbx_retake.py video/short3d/doorbell <lang> --short: Whisper listens to every line, weak lines get other seeds
3. build/<lang>/voice.wav (48 kHz mono) + build/<lang>/schedule.json:
   {"duration", "lines": [{"id", "vis", "text", "show", "t0", "t1", "words": [{"w", "t"}]}]} (Short seconds)
"""
import json
import subprocess
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import align  # noqa: E402
import cbx  # noqa: E402

SR = 48000
LANG = sys.argv[sys.argv.index("--lang") + 1] if "--lang" in sys.argv else "en"
# line -> shot: hook (flash-forward: tap RING on the phone, the packet flies, ding dong + "RING!"), noapp (no app /
# router / internet), wifi (the board's own Wi-Fi), join (the phone joins and opens 192.168.4.1), send (tap RING, the
# link flies, ding dong), colors (color buttons, the screen counts), parts (labels), cta (follow card)
VIS = {"l01": "hook", "l02": "noapp", "l03": "wifi", "l04": "join", "l05": "send", "l06": "send",
       "l07": "colors", "l08": "parts", "l09": "cta"}
GAP = 0.22


def build_spec():
    sc = {lg: json.loads((HERE / f"script_{lg}.json").read_text(encoding="utf-8")) for lg in ("en", "tr")}
    segs = []
    for i, ln in enumerate(sc["en"]["lines"]):
        tr = sc["tr"]["lines"][i]
        assert tr["id"] == ln["id"]
        s = {"id": ln["id"], "vis": VIS[ln["id"]], "say": {"en": ln["text"], "tr": tr["text"]},
             "show": {"en": ln.get("show", ln["text"]), "tr": tr.get("show", tr["text"])}}
        b = {lg: sc[lg].get("before", {}).get(ln["id"], 0.0) for lg in ("en", "tr")}
        s["before"] = b
        segs.append(s)
    spec = {"title": {lg: sc[lg]["title"] for lg in sc}, "project": sc["en"]["project"], "engine": "chatterbox",
            "lead": sc["en"].get("lead", 0.3), "gap": GAP, "tail": sc["en"].get("tail", 1.6),
            "note": "generated by voice.py from script_en.json + script_tr.json - edit those", "segments": segs}
    (HERE / "short.json").write_text(json.dumps(spec, indent=1, ensure_ascii=False), encoding="utf-8")
    return spec


spec = build_spec()
cfg = cbx.settings({}, LANG)
B = HERE / "build"
V = B / LANG
V.mkdir(parents=True, exist_ok=True)
cache_p = V / "cbx_cache.json"


def load_cache():
    return json.loads(cache_p.read_text(encoding="utf-8")) if cache_p.exists() else {}


def narrate():
    cache = load_cache()
    todo = []
    for s in spec["segments"]:
        text, mp3 = s["say"][LANG], V / f"{s['id']}.mp3"
        if cache.get(s["id"], {}).get("key") == cbx.key(cfg, text) and mp3.exists():
            continue
        todo.append((text, mp3))
    if todo:
        print(f"narrating {len(todo)} lines ({LANG})", flush=True)
        cbx.say(cfg, todo)
    for text, mp3 in todo:
        cache[mp3.stem] = {"key": cbx.key(cfg, text), "text": text,
                           "words": [w["t"] for w in align.align(mp3, text, LANG)]}
    cache_p.write_text(json.dumps(cache, indent=1, ensure_ascii=False), encoding="utf-8")


def decode(p):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(p), "-f", "f32le", "-ac", "1", "-ar", str(SR), "-"],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.float32)


def trim_tail(a, keep=0.12):
    """drop the quiet tail Chatterbox sometimes leaves after the last word (room noise, > 40 dB below the voice)"""
    hop = SR // 50
    fr = a[: len(a) // hop * hop].reshape(-1, hop)
    db = 10 * np.log10((fr ** 2).mean(1) + 1e-12)
    loud = np.where(db > db.max() - 40)[0]
    if not len(loud):
        return a
    end = min(len(a), (loud[-1] + 1) * hop + int(keep * SR))
    out = a[:end].copy()
    f = min(len(out), int(0.05 * SR))
    out[-f:] *= np.linspace(1, 0, f, dtype=np.float32)
    return out


def schedule():
    cache = load_cache()
    lead, gap, tail = spec["lead"], spec["gap"], spec["tail"]
    out, lines, t = [np.zeros(int(lead * SR), np.float32)], [], lead
    for s in spec["segments"]:
        pre = s["before"][LANG]
        if pre:
            out.append(np.zeros(int(pre * SR), np.float32))
            t += pre
        text, mp3 = s["say"][LANG], V / f"{s['id']}.mp3"
        a = trim_tail(decode(mp3))
        names = align.script_words(text)
        ts = cache.get(s["id"], {}).get("words")
        if not ts or len(ts) != len(names):
            ts = [w["t"] for w in align.align(mp3, text, LANG)]
        lines.append({"id": s["id"], "vis": s["vis"], "text": text, "show": s["show"][LANG], "t0": round(t, 3),
                      "t1": round(t + len(a) / SR, 3), "words": [{"w": w, "t": round(t + x, 3)} for w, x in zip(names, ts)]})
        out += [a, np.zeros(int(gap * SR), np.float32)]
        t += len(a) / SR + gap
    out.append(np.zeros(int(tail * SR), np.float32))
    t += tail
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "f32le", "-ar", str(SR), "-ac", "1", "-i", "-", str(V / "voice.wav")],
                   input=np.concatenate(out).tobytes(), check=True)
    (V / "schedule.json").write_text(json.dumps({"lang": LANG, "duration": round(t, 3), "lines": lines}, indent=1,
                                                ensure_ascii=False), encoding="utf-8")
    print(f"schedule.json ({LANG}): duration", round(t, 2), "s")


if __name__ == "__main__":
    if "--schedule" not in sys.argv:
        narrate()
        subprocess.run([sys.executable, str(ROOT / "tools" / "cbx_retake.py"), str(HERE.relative_to(ROOT)), LANG, "--short"],
                       cwd=ROOT, check=True)
    schedule()
